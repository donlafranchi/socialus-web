#!/usr/bin/env python3
"""Criterion reports. Each feature report's JSON sidecar is the truth; its Markdown tables and every roll-up are computed from it.
Usage:
  criteria.py check  <reports-dir>          validate every sidecar, and that each report's generated block matches it
  criteria.py render <sidecar.json>...      rewrite the generated block in the matching .md (creates the block if missing)
  criteria.py rollup <reports-dir>          check, then write <dir>/README.md and <dir>/rollup.json
  criteria.py diff   <old.json> <new.json>  cell-by-cell changes; lists criteria that disappeared
Anything it cannot read is listed on stderr and the exit code is 1. It never guesses."""
import json, os, re, sys
from datetime import date

SCHEMA = 1
PHASES = ['built', 'checked', 'reviewed', 'shipped', 'smoked', 'pm_looked']
LABEL = {'built': 'Built', 'checked': 'Checked', 'reviewed': 'Reviewed', 'shipped': 'Shipped', 'smoked': 'Smoked', 'pm_looked': 'PM looked'}
CELLS = ('yes', 'no', 'unknown')
KINDS = ('behavior', 'invariant', 'coverage', 'external')
STATUS = ('active', 'spec-conflict', 'retired')
FEATURE_KEYS = {'schema', 'feature', 'title', 'area', 'area_source', 'gates', 'retired', 'as_of', 'criteria'}
CRITERION_KEYS = {'id', 'text', 'kind', 'status', 'issues', 'note', *PHASES}
# Gap types in the order run-feature-pipeline takes them, and the skill each goes to.
GAPS = [
    ('SPEC-CONFLICT', '`scope-scenario`; `Path: new territory` goes to the PM as A/B/C'),
    ('UNKNOWN', '`regen-feature-report`: find the evidence'),
    ('NOT-BUILT', '`write-tickets` then `build-ticket`'),
    ('INVARIANT-UNPROVEN', '`write-tickets` (guard) then `build-ticket`'),
    ('NO-CHECK', '`write-tickets` (check) then `build-ticket`, tests seen failing'),
    ('NOT-REVIEWED', '`review-pr-bundle`'),
    ('NOT-SHIPPED', 'CI: `deploy-health` green on the merge commit'),
    ('NOT-SMOKED', 'CI: a `smoke-live` run that covers the route'),
    ('NOT-LOOKED', '`record-pm-review` (UAT Issue), after the rows above'),
]
START = '<!-- criteria:start · generated by criteria.py from the JSON sidecar; edit the JSON, never this block -->'
END = '<!-- criteria:end -->'


def gaps(c):
    """Derived from the cells, never stored: the same cells always route the same way."""
    if c['status'] == 'retired':
        return []
    if c['status'] == 'spec-conflict':
        return ['SPEC-CONFLICT']  # nothing is built or filed against it until it is ruled
    g = []
    if c['built'] == 'unknown':
        g.append('UNKNOWN')
    if c['built'] == 'no':
        g.append('NOT-BUILT')
    if c['built'] != 'yes':
        return g
    if c['checked'] != 'yes':
        g.append('INVARIANT-UNPROVEN' if 'invariant' in c['kind'] else 'NO-CHECK')
    for p, gap in (('reviewed', 'NOT-REVIEWED'), ('shipped', 'NOT-SHIPPED'), ('smoked', 'NOT-SMOKED'), ('pm_looked', 'NOT-LOOKED')):
        if c[p] != 'yes':
            g.append(gap)
    return g


def red(f, c):
    """Launch-gating blocker: a gates-launch feature whose criterion is not built, or an invariant with no standing guard."""
    return (f['gates'] == 'launch' and not f['retired'] and c['status'] != 'retired'
            and (c['built'] != 'yes' or ('invariant' in c['kind'] and c['checked'] != 'yes')))


def score(c):
    return sum(1 for p in PHASES if c[p] == 'yes')


def counted(f):
    return [c for c in f['criteria'] if c['status'] != 'retired']


def validate(f, where):
    e = []
    if not isinstance(f, dict):
        return [f'{where}: not a JSON object']
    for k in sorted(FEATURE_KEYS - f.keys()):
        e.append(f'{where}: missing "{k}"')
    for k in sorted(f.keys() - FEATURE_KEYS):
        e.append(f'{where}: unknown key "{k}"')
    if e:
        return e
    if f['schema'] != SCHEMA:
        e.append(f'{where}: schema {f["schema"]!r}, expected {SCHEMA}')
    if not re.fullmatch(r'F\d{3}', str(f['feature'])):
        e.append(f'{where}: feature {f["feature"]!r} is not F###')
    if not isinstance(f['title'], str) or not f['title'].strip():
        e.append(f'{where}: empty title')
    if not re.fullmatch(r'[a-z][a-z0-9-]*', str(f['area'])):
        e.append(f'{where}: area {f["area"]!r} is not a slug')
    if f['area_source'] not in ('label', 'guess'):
        e.append(f'{where}: area_source {f["area_source"]!r} not label/guess')
    if f['gates'] not in ('launch', 'none'):
        e.append(f'{where}: gates {f["gates"]!r} not launch/none')
    if not isinstance(f['retired'], bool):
        e.append(f'{where}: retired must be true/false')
    try:
        date.fromisoformat(str(f['as_of']))
    except ValueError:
        e.append(f'{where}: as_of {f["as_of"]!r} is not YYYY-MM-DD')
    if not isinstance(f['criteria'], list) or not f['criteria']:
        return e + [f'{where}: criteria must be a non-empty list']
    seen = set()
    for n, c in enumerate(f['criteria']):
        w = f'{where}: criteria[{n}]'
        if not isinstance(c, dict):
            e.append(f'{w}: not an object')
            continue
        for k in sorted(CRITERION_KEYS - c.keys()):
            e.append(f'{w}: missing "{k}"')
        for k in sorted(c.keys() - CRITERION_KEYS):
            e.append(f'{w}: unknown key "{k}"')
        if CRITERION_KEYS - c.keys():
            continue
        w = f'{where}: criterion {c["id"]}'
        if not re.fullmatch(r'\d+[a-z]?', str(c['id'])):
            e.append(f'{w}: id must be a number with an optional letter, e.g. "2b"')
        if c['id'] in seen:
            e.append(f'{w}: duplicate id')
        seen.add(c['id'])
        for p in PHASES:
            if c[p] not in CELLS:
                e.append(f'{w}: {p} is {c[p]!r}; a cell is yes, no or unknown (put detail in note)')
        if not isinstance(c['kind'], list) or not c['kind'] or any(k not in KINDS for k in c['kind']):
            e.append(f'{w}: kind {c["kind"]!r} must be a non-empty list of {", ".join(KINDS)}')
        if c['status'] not in STATUS:
            e.append(f'{w}: status {c["status"]!r} not in {", ".join(STATUS)}')
        if not isinstance(c['issues'], list) or any(not isinstance(i, int) or isinstance(i, bool) for i in c['issues']):
            e.append(f'{w}: issues must be a list of Issue numbers')
        for k in ('text', 'note'):
            if not isinstance(c[k], str) or '\n' in c[k]:
                e.append(f'{w}: {k} must be one line of text')
        if not c['text'].strip() if isinstance(c['text'], str) else False:
            e.append(f'{w}: empty text')
        if c['built'] == 'no' and any(c[p] != 'no' for p in ('shipped', 'smoked', 'pm_looked')):
            e.append(f'{w}: built is no, so shipped, smoked and PM looked must be no')
    return e


def load(path):
    try:
        f = json.load(open(path))
    except (OSError, ValueError) as x:
        return None, [f'{path}: cannot read JSON ({x})']
    return f, validate(f, path)


def cell(v):
    return {'yes': 'yes', 'no': '**no**', 'unknown': 'unknown'}[v]


def esc(s):
    return s.replace('|', '\\|')


def tally(cs):
    return {p: {v: sum(1 for c in cs if c[p] == v) for v in CELLS} for p in PHASES}


def frac(t, n):
    s = f'{t["yes"]}/{n}'
    return s + (f' ({t["unknown"]}?)' if t['unknown'] else '')


def block(f):
    cs = counted(f)
    t = tally(cs)
    ids = lambda pred: ', '.join(c['id'] for c in cs if pred(c)) or 'none'
    out = [START, '', '## Roll-up', '',
           '| | ' + ' | '.join(LABEL[p] for p in PHASES) + ' |', '|---' * (len(PHASES) + 1) + '|',
           f'| {len(cs)} criteria | ' + ' | '.join(frac(t[p], len(cs)) for p in PHASES) + ' |', '',
           f'Not built: {ids(lambda c: c["built"] == "no")}. Built unknown: {ids(lambda c: c["built"] == "unknown")}. '
           f'Spec conflict: {ids(lambda c: c["status"] == "spec-conflict")}.'
           + (f' Launch blockers: {ids(lambda c: red(f, c))}.' if f['gates'] == 'launch' else '')
           + (f' Retired criteria (not counted): {", ".join(c["id"] for c in f["criteria"] if c["status"] == "retired")}.'
              if len(cs) < len(f['criteria']) else ''),
           '', '## Per criterion', '',
           '| # | In plain words | Kind | Status | ' + ' | '.join(LABEL[p] for p in PHASES) + ' | Issues | What exists / what is missing |',
           '|---' * (len(PHASES) + 6) + '|']
    for c in f['criteria']:
        out.append(f'| {c["id"]} | {esc(c["text"])} | {" + ".join(c["kind"])} | {c["status"]} | '
                   + ' | '.join(cell(c[p]) for p in PHASES) + ' | '
                   + (', '.join(f'#{i}' for i in c['issues']) or 'none') + f' | {esc(c["note"])} |')
    out += ['', '## Routing', '', '| Gap | Criteria | Next skill |', '|---|---|---|']
    for g, skill in GAPS:
        hit = [c['id'] for c in cs if g in gaps(c)]
        if hit:
            out.append(f'| {g} | {", ".join(hit)} | {skill} |')
    return '\n'.join(out + ['', END])


def md_path(j):
    return j[:-5] + '.md'


def render(j):
    f, e = load(j)
    if e:
        return e
    m = md_path(j)
    text = open(m).read() if os.path.exists(m) else f'# {f["feature"]}: {f["title"]}\n'
    b = block(f)
    if START in text and END in text:
        text = text[:text.index(START)] + b + text[text.index(END) + len(END):]
    else:
        text = text.rstrip('\n') + '\n\n' + b + '\n'
    open(m, 'w').write(text)
    return []


def reports(d):
    out = []
    for area in sorted(os.listdir(d)):
        p = os.path.join(d, area)
        if os.path.isdir(p):
            out += [os.path.join(p, x) for x in sorted(os.listdir(p)) if x.endswith(('.md', '.json'))]
    return out


def check(d):
    errs, feats = [], []
    files = reports(d)
    for p in files:
        stem, ext = os.path.splitext(p)
        twin = stem + ('.json' if ext == '.md' else '.md')
        if twin not in files:
            errs.append(f'{p}: no {os.path.basename(twin)} beside it')
        if ext != '.json':
            continue
        f, e = load(p)
        errs += e
        if e:
            continue
        area, name = os.path.basename(os.path.dirname(p)), os.path.basename(stem)
        if not name.startswith(f['feature'] + '-'):
            errs.append(f'{p}: file name must start with "{f["feature"]}-"')
        if area != f['area']:
            errs.append(f'{p}: sits in {area}/ but area is {f["area"]!r}')
        if os.path.exists(twin):
            t = open(twin).read()
            if START not in t or END not in t:
                errs.append(f'{twin}: no generated block; run criteria.py render {p}')
            elif t[t.index(START):t.index(END) + len(END)] != block(f):
                errs.append(f'{twin}: generated block does not match the JSON; run criteria.py render {p}')
        f['path'] = os.path.relpath(stem + '.md', d)
        feats.append(f)
    dup = {f['feature'] for f in feats if sum(1 for g in feats if g['feature'] == f['feature']) > 1}
    errs += [f'{x}: more than one report' for x in sorted(dup)]
    return feats, errs


def rollup(d):
    feats, errs = check(d)
    if errs:
        return errs
    zero = {p: {v: 0 for v in CELLS} for p in PHASES}
    out_f, areas, gap_ix, problems, per = [], {}, {g: [] for g, _ in GAPS}, [], []
    for f in sorted(feats, key=lambda f: (f['area'], f['feature'])):
        cs = counted(f)
        t = tally(cs)
        rows = [{**c, 'gaps': gaps(c), 'score': score(c), 'red': red(f, c)} for c in f['criteria']]
        out_f.append({k: f[k] for k in ('feature', 'title', 'area', 'area_source', 'gates', 'retired', 'as_of', 'path')}
                     | {'n': len(cs), 'totals': t, 'red': sum(1 for r in rows if r['red']), 'criteria': rows})
        if f['retired']:
            problems.append(f'{f["feature"]}: scenario retired; shown, not counted')
            continue
        a = areas.setdefault(f['area'], {'features': 0, 'n': 0, 'red': 0, 'totals': json.loads(json.dumps(zero))})
        a['features'] += 1
        a['n'] += len(cs)
        a['red'] += out_f[-1]['red']
        for p in PHASES:
            for v in CELLS:
                a['totals'][p][v] += t[p][v]
        for r in rows:
            for g in r['gaps']:
                gap_ix[g].append(f'{f["feature"]}.{r["id"]}')
        if f['area_source'] == 'guess':
            problems.append(f'{f["feature"]}: area {f["area"]!r} is a guess; no Issue carries an area: label')
        unk = [p for p in PHASES if t[p]['unknown']]
        if unk:
            per.append((f['feature'], {p: t[p]['unknown'] for p in unk}))
    # A phase unknown on every built criterion is one system problem, not one per feature.
    live = [c for f in feats if not f['retired'] for c in counted(f)]
    built = [c for c in live if c['built'] != 'no']
    whole = [p for p in PHASES if p != 'built' and built and all(c[p] == 'unknown' for c in built)]
    for p in whole:
        problems.insert(0, f'{LABEL[p]} is unknown on all {len(built)} criteria that are built or may be: no evidence source for it yet')
    for feat, u in per:
        rest = [f'{LABEL[p]} {n}' for p, n in u.items() if p not in whole]
        if rest:
            problems.append(f'{feat}: unknown cells: ' + ', '.join(rest))
    total = {'features': sum(a['features'] for a in areas.values()), 'n': sum(a['n'] for a in areas.values()),
             'red': sum(a['red'] for a in areas.values()),
             'totals': {p: {v: sum(a['totals'][p][v] for a in areas.values()) for v in CELLS} for p in PHASES}}
    data = {'schema': SCHEMA, 'phases': PHASES, 'as_of': max(f['as_of'] for f in feats), 'features': out_f,
            'areas': areas, 'all': total, 'gaps': {g: v for g, v in gap_ix.items() if v}, 'problems': problems}
    json.dump(data, open(os.path.join(d, 'rollup.json'), 'w'), indent=1, ensure_ascii=False)
    open(os.path.join(d, 'rollup.json'), 'a').write('\n')
    head = '| | Criteria | ' + ' | '.join(LABEL[p] for p in PHASES) + ' | Launch blockers |'
    sep = '|---' * (len(PHASES) + 3) + '|'
    row = lambda name, x: f'| {name} | {x["n"]} | ' + ' | '.join(frac(x['totals'][p], x['n']) for p in PHASES) + f' | {x["red"]} |'
    md = ['# Feature reports: roll-up', '',
          f'*Generated by `scripts/criteria.py rollup` from the JSON sidecars; never hand-edited. as-of {data["as_of"]}. '
          'Each cell is criteria at `yes` out of criteria counted; `(n?)` is how many are `unknown`, never counted as yes. '
          'Retired scenarios are listed, not counted. Machine-readable: `rollup.json`.*', '',
          '## By area', '', head, sep, *[row(a, x) for a, x in sorted(areas.items())], row('**All**', total), '',
          '## By feature', '', '| Area | Feature | Gates | Criteria | ' + ' | '.join(LABEL[p] for p in PHASES) + ' | Launch blockers |',
          '|---' * (len(PHASES) + 5) + '|']
    for f in out_f:
        name = f'[{f["feature"]} {f["title"]}]({f["path"]})' + (' (retired, not counted)' if f['retired'] else '')
        md.append(f'| {f["area"]} | {name} | {f["gates"]} | {f["n"]} | ' + ' | '.join(frac(f['totals'][p], f['n']) for p in PHASES) + f' | {f["red"]} |')
    md += ['', '## Gaps by type', '', '| Gap | Count | Criteria | Next skill |', '|---|---|---|---|']
    for g, skill in GAPS:
        if gap_ix[g]:
            shown = ', '.join(gap_ix[g]) if len(gap_ix[g]) <= 40 else ', '.join(gap_ix[g][:40]) + f', … ({len(gap_ix[g]) - 40} more)'
            md.append(f'| {g} | {len(gap_ix[g])} | {shown} | {skill} |')
    md += ['', '## Data problems', ''] + [f'- {p}' for p in problems] + ([] if problems else ['- none'])
    open(os.path.join(d, 'README.md'), 'w').write('\n'.join(md) + '\n')
    print(f'rollup: {total["features"]} features, {total["n"]} criteria, {total["red"]} launch blockers, {len(problems)} data problems')
    return []


def diff(a, b):
    fa, ea = load(a)
    fb, eb = load(b)
    if ea or eb:
        return ea + eb
    old, new = {c['id']: c for c in fa['criteria']}, {c['id']: c for c in fb['criteria']}
    for i in old:
        if i not in new:
            print(f'LOST criterion {i}: {old[i]["text"]}')
    for i in new:
        if i not in old:
            print(f'NEW criterion {i}: {new[i]["text"]}')
            continue
        for k in ['text', 'kind', 'status', *PHASES, 'issues']:
            if old[i][k] != new[i][k]:
                print(f'{i}.{k}: {old[i][k]!r} -> {new[i][k]!r}')
    for k in ('area', 'area_source', 'gates', 'retired'):
        if fa[k] != fb[k]:
            print(f'{k}: {fa[k]!r} -> {fb[k]!r}')
    return []


def main(argv):
    if len(argv) < 2 or argv[0] not in ('check', 'render', 'rollup', 'diff'):
        print(__doc__, file=sys.stderr)
        return 2
    cmd, args = argv[0], argv[1:]
    if cmd == 'check':
        feats, errs = check(args[0])
        if not errs:
            print(f'check: {len(feats)} reports, all readable')
    elif cmd == 'render':
        errs = [e for j in args for e in render(j)]
    elif cmd == 'rollup':
        errs = rollup(args[0])
    else:
        errs = diff(*args[:2])
    for e in errs:
        print('criteria.py: ' + e, file=sys.stderr)
    if errs:
        print(f'criteria.py: {len(errs)} problem(s); nothing was guessed', file=sys.stderr)
    return 1 if errs else 0


if __name__ == '__main__':
    sys.exit(main(sys.argv[1:]))
