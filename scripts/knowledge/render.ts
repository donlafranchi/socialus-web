// F125 / T1017 (#1218) — constraints/<tier>.md, written from rows.
//
// The layout is socialus-plan scripts/markers.py's render_constraints, word
// for word, so the file the store exports and the file markers.py builds can
// be compared line for line (F125.1). The rows come from the store
// (export.ts); the test also feeds it rows straight from the parser, so a
// difference shows whether the parser or the store lost something.

/** The day tagging became required (markers.py BINDS_FROM). */
export const BINDS_FROM = '2026-09-21'

export interface ConstraintRow {
  date: string
  holds: 'always' | 'for now' | null
  /** null: carries no binds tag; [] for tiers=none. */
  tiers: string[] | null
  surfaces: string[]
  words: string
  file: string
  line: number
}

const byCodePoint = (a: string, b: string) => (a < b ? -1 : a > b ? 1 : 0)

export function renderConstraints(tier: string, rows: ConstraintRow[]): string {
  // markers.py reads files in code-point order and lines in order, then sorts
  // by date, newest first; Python's sort is stable, so ties keep file order.
  const ordered = [...rows].sort((a, b) => byCodePoint(a.file, b.file) || a.line - b.line)
  const listed = ordered
    .filter((r) => r.tiers?.includes(tier))
    .sort((a, b) => byCodePoint(b.date, a.date))
  const untagged = rows.filter((r) => r.tiers === null).length
  const o = [
    `# CONSTRAINTS — ${tier} tier`,
    '',
    '> **Generated by `python3 scripts/markers.py constraints` — never edit this file.** A hand edit is',
    '> lost on the next run, and `scripts/lint.sh` fails whenever this file differs from what',
    '> the rulings generate (`PRINCIPLES.md`, and `## Rulings` in each scenario and product doc). To change it, change the `[binds …]` tag on the decision.',
    '>',
    `> Every ratified decision whose tag binds the **${tier}** tier, newest first. The rulings hold`,
    '> only live decisions — a superseded one is deleted — so nothing below conflicts with anything',
    '> else here. If two lines ever seem to, the newer wins (`[newer-decision-wins]`).',
    `> **${untagged} older decisions carry no tag yet and are not listed** — tagging is required from`,
    `> ${BINDS_FROM} onward. Absent here is not the same as not binding.`,
    '',
  ]
  const lines = listed.map(
    (e) =>
      `- **${e.date}**${e.holds ? ` · [${e.holds}]` : ''} · ${e.surfaces.join(', ')} — ${e.words.replace(/\.+$/, '')} (${e.file})`,
  )
  return [...o, ...(lines.length ? lines : ['None tagged.'])].join('\n') + '\n'
}
