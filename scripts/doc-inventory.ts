// Rebuilds docs/DOC-INVENTORY.md: every tracked .md in the repo, with the facts
// a script can know (last commit, as-of date, generated or hand-written, broken
// links, references to files and npm scripts that no longer exist) joined to the
// judgments a person made (docs/doc-inventory.judgments.json: purpose, one stale
// example, duplicate, recommendation).
//
// Run: npm run docs:inventory           (rewrite the file)
//      npm run docs:inventory -- --check (exit 1 if the committed file is out of date)
//
// The output is deterministic for a given repo state and date, so a later run
// diffs cleanly against the committed one. A doc with no judgment, or changed
// since its judgment, shows as "needs review": that list is the periodic review.

import { execFileSync } from 'node:child_process'
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, normalize } from 'node:path'

export type DocClass =
  | 'doc'
  | 'readme'
  | 'template'
  | 'feature-report'
  | 'fixture'

export interface Judgment {
  purpose: string
  origin: 'hand' | 'generated'
  stale?: string
  duplicate?: string
  rec: 'keep' | 'refresh' | 'merge' | 'delete' | 'generate'
  note?: string
  reviewed: string
}

export const OUT = 'docs/DOC-INVENTORY.md'
export const JUDGMENTS = 'docs/doc-inventory.judgments.json'
export const AGING_DAYS = 21
export const STALE_DAYS = 45

export function classify(p: string): DocClass {
  if (p.startsWith('build-log/reports/')) return 'feature-report'
  if (p.startsWith('scripts/fixtures/')) return 'fixture'
  if (p.startsWith('.github/')) return 'template'
  if (/(^|\/)README\.md$/.test(p)) return 'readme'
  return 'doc'
}

const ASOF = [
  /\bas[- ]of:?\s+\**(\d{4}-\d{2}-\d{2})/i,
  /\blast (?:updated|changed|verified):?\s+\**(\d{4}-\d{2}-\d{2})/i,
  /\bupdated:?\s+\**(\d{4}-\d{2}-\d{2})/i,
  /\bproduced\s+(\d{4}-\d{2}-\d{2})/i,
  /^\*(\d{4}-\d{2}-\d{2})\b/m,
]

export function asOfDate(text: string): string | null {
  const head = text.split('\n').slice(0, 30).join('\n')
  for (const re of ASOF) {
    const m = head.match(re)
    if (m) return m[1]!
  }
  return null
}

// The one-line header every state-describing doc carries (socialus-ops README, "How our work is structured").
export function standardHeader(text: string): boolean {
  return /\*\*As of \d{4}-\d{2}-\d{2}\*\*.*Source:.*(Generated by|Maintained by):/i.test(text.split('\n').slice(0, 15).join('\n'))
}

export function looksGenerated(text: string): boolean {
  return /\b(regenerated|auto-?generated|generated by|do not edit)\b/i.test(text.split('\n').slice(0, 12).join('\n'))
}

function stripFences(text: string): string {
  return text.replace(/```[\s\S]*?```/g, '')
}

export function relativeLinks(text: string): string[] {
  const out: string[] = []
  for (const m of stripFences(text).matchAll(/\[[^\]]*\]\(([^)\s]+)(?:\s+"[^"]*")?\)/g)) {
    const t = m[1]!
    if (/^(https?:|mailto:|#|tel:)/.test(t)) continue
    out.push(t.split('#')[0]!.replace(/%20/g, ' '))
  }
  return out.filter(Boolean)
}

const PATH_REF = /`((?:src|scripts|supabase|docs|evals|tests|build-log|\.github)\/[A-Za-z0-9_./()@-]+\.[A-Za-z0-9]+)`/g

export function pathRefs(text: string): string[] {
  const out = new Set<string>()
  for (const m of stripFences(text).matchAll(PATH_REF)) out.add(m[1]!)
  return [...out]
}

export function npmScriptRefs(text: string): string[] {
  const out = new Set<string>()
  for (const m of text.matchAll(/\bnpm run ([a-z][\w:-]*)/g)) out.add(m[1]!)
  return [...out]
}

function git(args: string[]): string {
  return execFileSync('git', args, { encoding: 'utf8', maxBuffer: 64 * 1024 * 1024 })
}

function lastCommitDates(): Map<string, string> {
  const dates = new Map<string, string>()
  let cur = ''
  for (const line of git(['log', '--format=%x01%cs', '--name-only', '--diff-filter=AMR', '--', '*.md']).split('\n')) {
    if (line.startsWith('\x01')) cur = line.slice(1)
    else if (line && !dates.has(line)) dates.set(line, cur)
  }
  return dates
}

function daysBetween(a: string, b: string): number {
  return Math.round((Date.parse(b) - Date.parse(a)) / 86_400_000)
}

interface Row {
  path: string
  cls: DocClass
  lines: number
  last: string
  asOf: string | null
  generated: boolean
  brokenLinks: string[]
  deadPaths: string[]
  deadScripts: string[]
  age: number
  j: Judgment | undefined
  flags: string[]
}

export function build(today: string, root = '.'): { rows: Row[]; md: string } {
  const files = git(['ls-files', '-z', '*.md']).split('\0').filter(Boolean).sort()
  const dates = lastCommitDates()
  const pkg = JSON.parse(readFileSync(join(root, 'package.json'), 'utf8')) as { scripts: Record<string, string> }
  const judgments: Record<string, Judgment> = existsSync(join(root, JUDGMENTS))
    ? (JSON.parse(readFileSync(join(root, JUDGMENTS), 'utf8')) as Record<string, Judgment>)
    : {}

  const rows: Row[] = files.map((p) => {
    const text = readFileSync(join(root, p), 'utf8')
    const cls = classify(p)
    const self = p === OUT
    const last = dates.get(p) ?? today
    const brokenLinks = self ? [] : relativeLinks(text).filter((t) => !existsSync(join(root, t.startsWith('/') ? t.slice(1) : normalize(join(dirname(p), t)))))
    const history = cls === 'fixture'
    const deadPaths = history || self ? [] : pathRefs(text).filter((t) => !existsSync(join(root, t)))
    const deadScripts = history || self ? [] : npmScriptRefs(text).filter((s) => !(s in pkg.scripts) && !['install', 'ci', 'test', 'start'].includes(s))
    const j = judgments[p]
    const handWritten = cls === 'doc' || cls === 'readme' || cls === 'template'
    const generated = looksGenerated(text) || cls === 'feature-report'
    const asOf = asOfDate(text)
    const age = daysBetween(asOf && asOf < last ? asOf : last, today) // a stamped as-of date keeps the doc's real age; the stamp commit does not reset it
    const flags: string[] = []
    if ((cls === 'doc' || cls === 'readme') && !generated && !asOf) flags.push('undated')
    if ((cls === 'doc' || cls === 'readme') && !/(^|\/)(CLAUDE|AGENTS)\.md$/.test(p) && !standardHeader(text)) flags.push('no standard header')
    if (brokenLinks.length) flags.push(`${brokenLinks.length} broken link${brokenLinks.length > 1 ? 's' : ''}`)
    if (deadPaths.length) flags.push(`${deadPaths.length} dead path${deadPaths.length > 1 ? 's' : ''}`)
    if (deadScripts.length) flags.push(`${deadScripts.length} dead npm script${deadScripts.length > 1 ? 's' : ''}`)
    if (handWritten && !generated && age > STALE_DAYS) flags.push(`stale (${age}d)`)
    else if (handWritten && !generated && age > AGING_DAYS) flags.push(`aging (${age}d)`)
    if (handWritten && !j) flags.push('needs review')
    else if (handWritten && j && j.reviewed < last) flags.push('changed since review')
    return { path: p, cls, lines: text.split('\n').length, last, asOf, generated, brokenLinks, deadPaths, deadScripts, age, j, flags }
  })

  return { rows, md: render(rows, today) }
}

const esc = (s: string) => s.replace(/\|/g, '\\|').replace(/\n/g, ' ')

function render(rows: Row[], today: string): string {
  const curated = rows.filter((r) => ['doc', 'readme', 'template'].includes(r.cls))
  const byClass = (c: DocClass) => rows.filter((r) => r.cls === c)
  const undated = curated.filter((r) => r.flags.includes('undated'))
  const nonStandard = curated.filter((r) => r.flags.includes('no standard header'))
  const stale = curated.filter((r) => r.flags.some((f) => f.startsWith('stale')))
  const aging = curated.filter((r) => r.flags.some((f) => f.startsWith('aging')))
  const broken = rows.filter((r) => r.brokenLinks.length)
  const dead = rows.filter((r) => r.deadPaths.length || r.deadScripts.length)
  const need = curated.filter((r) => r.flags.includes('needs review') || r.flags.includes('changed since review'))
  const recs = (k: string) => curated.filter((r) => r.j?.rec === k)

  const o: string[] = []
  o.push('# Doc inventory')
  o.push('')
  o.push(`**As of ${today}.** Generated by \`npm run docs:inventory\` (\`scripts/doc-inventory.ts\`); do not edit by hand. Judgments live in \`docs/doc-inventory.judgments.json\`; everything else is read from git and the files.`)
  o.push('')
  o.push('Re-run it, commit the result, and read the diff: that is the periodic review. A doc with no judgment, or changed since its judgment, is listed under *Needs review*. Hand-written docs older than ' + AGING_DAYS + ' days show as aging, older than ' + STALE_DAYS + ' as stale.')
  o.push('')
  o.push('## Counts')
  o.push('')
  o.push('| | |')
  o.push('|---|---|')
  o.push(`| Docs tracked | ${rows.length} |`)
  o.push(`| Curated (hand-written READMEs, runbooks, docs, templates) | ${curated.length} |`)
  o.push(`| Feature reports (generated) | ${byClass('feature-report').length} |`)
  o.push(`| Test fixtures | ${byClass('fixture').length} |`)
  o.push(`| Curated, undated | ${undated.length} |`)
  o.push(`| Curated, not in the standard header | ${nonStandard.length} |`)
  o.push(`| Curated, stale or aging | ${stale.length} stale, ${aging.length} aging |`)
  o.push(`| Docs with broken links | ${broken.length} |`)
  o.push(`| Docs with dead path or npm-script references | ${dead.length} |`)
  o.push(`| Needs review | ${need.length} |`)
  o.push(`| Recommendation: keep ${recs('keep').length}, refresh ${recs('refresh').length}, merge ${recs('merge').length}, delete ${recs('delete').length}, generate ${recs('generate').length} | |`)
  o.push('')

  const list = (title: string, rs: Row[], f: (r: Row) => string) => {
    o.push(`## ${title}`)
    o.push('')
    if (!rs.length) o.push('None.')
    for (const r of rs) o.push(`- \`${r.path}\`${f(r)}`)
    o.push('')
  }
  list('Needs review', need, (r) => (r.j ? ` (reviewed ${r.j.reviewed}, last changed ${r.last})` : ' (no judgment yet)'))
  list('Undated', undated, (r) => ` (last changed ${r.last})`)
  list('Stale or aging', [...stale, ...aging], (r) => ` (as of ${r.asOf && r.asOf < r.last ? r.asOf : r.last}, ${r.age} days)`)
  list('Broken links', broken, (r) => `: ${r.brokenLinks.map((l) => `\`${l}\``).join(', ')}`)
  list('Dead references', dead, (r) => `: ${[...r.deadPaths, ...r.deadScripts.map((s) => `npm run ${s}`)].map((l) => `\`${l}\``).join(', ')}`)

  o.push('## Curated docs')
  o.push('')
  o.push('| Path | Purpose | Origin | Last change | As of | Stale or contradicted (one example) | Duplicated in | Recommendation | Flags |')
  o.push('|---|---|---|---|---|---|---|---|---|')
  for (const r of curated) {
    const j = r.j
    o.push(
      `| \`${r.path}\` | ${esc(j?.purpose ?? '')} | ${j?.origin ?? (r.generated ? 'generated' : 'hand')} | ${r.last} | ${r.asOf ?? 'none'} | ${esc(j?.stale ?? '')} | ${esc(j?.duplicate ?? '')} | ${j?.rec ?? ''}${j?.note ? ': ' + esc(j.note) : ''} | ${r.flags.join(', ')} |`,
    )
  }
  o.push('')

  o.push('## Classes (not listed one by one)')
  o.push('')
  o.push('| Class | Where | Count | Newest | Origin | Recommendation |')
  o.push('|---|---|---|---|---|---|')
  const classRow = (c: DocClass, where: string, origin: string, rec: string) => {
    const rs = byClass(c)
    if (!rs.length) return
    const newest = rs.map((r) => r.last).sort().at(-1)
    o.push(`| ${c} | ${where} | ${rs.length} | ${newest} | ${origin} | ${rec} |`)
  }
  classRow('feature-report', '`build-log/reports/**`', 'generated by the feature-reports run (each carries as-of)', 'keep; regenerated whole by that run')
  classRow('fixture', '`scripts/fixtures/**`', 'test inputs', 'exclude from freshness checks')
  o.push('')
  return o.join('\n') + '\n'
}

function main() {
  const args = process.argv.slice(2)
  const dateArg = args.find((a) => a.startsWith('--date='))?.slice(7)
  const today = dateArg ?? new Date().toISOString().slice(0, 10)
  const { md } = build(today)
  if (args.includes('--check')) {
    const cur = existsSync(OUT) ? readFileSync(OUT, 'utf8') : ''
    const strip = (s: string) => s.replace(/\*\*As of \d{4}-\d{2}-\d{2}\.\*\*/, '').replace(/\(\d+d\)|\d+ days/g, '')
    if (strip(cur) !== strip(md)) {
      console.error(`${OUT} is out of date. Run: npm run docs:inventory`)
      process.exit(1)
    }
    console.log(`${OUT} is current`)
    return
  }
  writeFileSync(OUT, md)
  console.log(`wrote ${OUT}`)
}

if (process.argv[1] && process.argv[1].endsWith('doc-inventory.ts')) main()
