#!/usr/bin/env tsx
// Writes supabase/migrations/<version>_zip_county.sql from the Census 2020 ZCTA relationship files:
// zip → county (the county with the largest land share of the zip), and, only inside a county that
// markets split (market_members rows with a cousub), zip → county subdivision (largest share).
// Census now, HUD-USPS later (the PM, 2026-10-12, #693): swap the source, keep the tables.
//   usage: tsx scripts/generate-zip-county-migration.ts <version> [--local <dir>]
import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { resolve, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const REL = 'https://www2.census.gov/geo/docs/maps-data/data/rel2020/zcta520'
const GAZ = 'https://www2.census.gov/geo/docs/maps-data/data/gazetteer/2023_Gazetteer'
// Counties that markets split (Placer, El Dorado): only their zips need a subdivision.
const SPLIT = new Set(['06061', '06017'])

const [version, flag, dir] = process.argv.slice(2)
if (!version) throw new Error('usage: generate-zip-county-migration.ts <version> [--local <dir>]')

async function text(name: string, url: string): Promise<string> {
  if (flag === '--local' && dir && existsSync(join(dir, name))) return readFileSync(join(dir, name), 'utf8')
  const res = await fetch(url)
  if (!res.ok) throw new Error(`${url}: ${res.status}`)
  return res.text()
}

const rows = (t: string) => t.replace(/^﻿/, '').split(/\r?\n/).filter(Boolean).map((l) => l.split(/[|\t]/))

// Column positions from each header, so a reordered file fails loudly rather than silently.
const col = (h: string[], n: string) => {
  const i = h.indexOf(n)
  if (i < 0) throw new Error(`missing column ${n}`)
  return i
}
function largest(file: string[][], zipCol: string, partCol: string, idCol: string): Map<string, string> {
  const h = file[0]!
  const z = col(h, zipCol), g = col(h, idCol), a = col(h, partCol)
  const best = new Map<string, { id: string; area: number }>()
  for (const r of file.slice(1)) {
    const zip = r[z]!
    if (!/^\d{5}$/.test(zip)) continue // the rows with no ZCTA are land outside every zip
    const area = Number(r[a])
    const cur = best.get(zip)
    // Largest share wins; a tie goes to the lower code so the same zip always gives the same answer.
    if (!cur || area > cur.area || (area === cur.area && r[g]! < cur.id)) best.set(zip, { id: r[g]!, area })
  }
  return new Map([...best].map(([k, v]) => [k, v.id]))
}

async function main() {
const zipCounty = rows(await text('tab20_zcta520_county20_natl.txt', `${REL}/tab20_zcta520_county20_natl.txt`))
const zipCousub = rows(await text('tab20_zcta520_cousub20_natl.txt', `${REL}/tab20_zcta520_cousub20_natl.txt`))

const county = largest(zipCounty, 'GEOID_ZCTA5_20', 'AREALAND_PART', 'GEOID_COUNTY_20')
  const cousub = largest(zipCousub, 'GEOID_ZCTA5_20', 'AREALAND_PART', 'GEOID_COUSUB_20')
  
  const gaz = rows(await text('2023_Gaz_counties_national.txt', `${GAZ}/2023_Gaz_counties_national.txt`))
  const names = gaz.slice(1).map((r) => ({ fips: r[1]!.trim(), name: r[3]!.trim(), state: r[0]!.trim() }))
  
  const q = (s: string) => `'${s.replace(/'/g, "''")}'`
  // The gazetteer lists the states and DC only: zips in the territories (PR, VI, GU, AS, MP) are left out, so they are unknown.
  const known = new Set(names.map((n) => n.fips))
  const zips = [...county].filter(([, c]) => known.has(c)).sort(([a], [b]) => (a < b ? -1 : 1))
  const lines: string[] = [
    `-- F103.2 (#694): zip → county → market. Generated by scripts/generate-zip-county-migration.ts from the`,
    `-- Census 2020 ZCTA relationship files (largest land share wins). Census now, HUD-USPS later (the PM, 2026-10-12).`,
    `-- A ZCTA is a Census approximation of a zip: a zip with no ZCTA (a PO-box-only zip) is unknown here.`,
    ``,
    `create table public.counties (`,
    `  fips  text primary key check (fips ~ '^[0-9]{5}$'),`,
    `  name  text not null,`,
    `  state text not null check (state ~ '^[A-Z]{2}$')`,
    `);`,
    `create table public.zip_county (`,
    `  zip          text primary key check (zip ~ '^[0-9]{5}$'),`,
    `  county_fips  text not null references public.counties(fips),`,
    `  -- Set only inside a county that a market splits.`,
    `  cousub_geoid text check (cousub_geoid ~ '^[0-9]{10}$')`,
    `);`,
    `alter table public.counties enable row level security;`,
    `alter table public.zip_county enable row level security;`,
    `create policy counties_select_public on public.counties for select using (true);`,
    `create policy zip_county_select_public on public.zip_county for select using (true);`,
    ``,
    `insert into public.counties (fips, name, state) values`,
    names.map((n) => `(${q(n.fips)},${q(n.name)},${q(n.state)})`).join(',\n') + ';',
    ``,
  ]
  lines.push(
    ``,
    `-- Waiting markets get a metro_polygons row the first time someone waits (the feed, the waitlist and its counts`,
    `-- already read that table; it is retired in the first fortnight after beta). code_kind 'market' marks them.`,
    `alter table public.metro_polygons drop constraint metro_polygons_code_kind_check;`,
    `alter table public.metro_polygons add constraint metro_polygons_code_kind_check check (code_kind in ('csa', 'cbsa', 'market'));`,
    ``,
    `-- Tahoe waits from day one: its state row exists, linked from the market.`,
    `insert into public.metro_polygons (name, slug, csa_code, code_kind) values ('Lake Tahoe', 'tahoe', 'market:tahoe', 'market');`,
    `update public.markets set metro_id = (select id from public.metro_polygons where slug = 'tahoe') where slug = 'tahoe';`,
    ``,
    `create function public.zip_market_key(p_zip text)`,
    `returns text language sql stable set search_path = public as $$`,
    `  select public.market_key(z.county_fips, z.cousub_geoid) from public.zip_county z where z.zip = p_zip`,
    `$$;`,
    ``,
    `create function public.market_name(p_key text)`,
    `returns text language sql stable set search_path = public as $$`,
    `  select coalesce(`,
    `    (select m.name from public.markets m where m.slug = p_key),`,
    `    (select c.name || ', ' || c.state from public.counties c where p_key = 'county-' || c.fips)`,
    `  )`,
    `$$;`,
    ``,
    `-- The metro_polygons row a market waits on. Idempotent, and bounded: only a named market or a real county.`,
    `create function public.market_metro(p_key text)`,
    `returns uuid language plpgsql security definer set search_path = public as $$`,
    `declare v uuid; v_name text;`,
    `begin`,
    `  select m.metro_id into v from public.markets m where m.slug = p_key and m.metro_id is not null;`,
    `  if v is not null then return v; end if;`,
    `  select id into v from public.metro_polygons where slug = p_key;`,
    `  if v is not null then return v; end if;`,
    `  v_name := case when p_key ~ '^county-[0-9]{5}$' then public.market_name(p_key) end;`,
    `  if v_name is null then return null; end if;`,
    `  insert into public.metro_polygons (name, slug, csa_code, code_kind) values (v_name, p_key, 'market:' || p_key, 'market') on conflict (slug) do nothing;`,
    `  select id into v from public.metro_polygons where slug = p_key;`,
    `  return v;`,
    `end $$;`,
    `revoke all on function public.market_metro(text) from public;`,
    `grant execute on function public.market_metro(text) to anon, authenticated, service_role;`,
  )
  for (let i = 0; i < zips.length; i += 1000) {
    lines.push(`insert into public.zip_county (zip, county_fips, cousub_geoid) values`)
    lines.push(
      zips
        .slice(i, i + 1000)
        .map(([zip, c]) => `('${zip}','${c}',${SPLIT.has(c) && cousub.get(zip) ? q(cousub.get(zip)!) : 'null'})`)
        .join(',\n') + ';',
    )
  }
  writeFileSync(resolve(ROOT, 'supabase', 'migrations', `${version}_zip_county.sql`), lines.join('\n') + '\n')
  console.log(`wrote ${zips.length} zips, ${names.length} counties`)
}
main()
