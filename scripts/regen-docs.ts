// Regenerates the docs that can be derived from the repo, so nobody maintains them:
//   BUILD-LOG.md      the index of weekly build-log folders (written whole)
//   TEST-CHECKLIST.md the Playwright eval table (the region between the eval-table markers)
//
// Run: npm run docs:regen            (rewrite both)
//      npm run docs:regen -- --check (exit 1 if either is out of date)
// The weekly regen-doc-inventory skill runs this, then npm run docs:inventory.

import { execFileSync } from 'node:child_process'
import { existsSync, readdirSync, readFileSync, writeFileSync } from 'node:fs'

const git = (args: string[]) => execFileSync('git', args, { encoding: 'utf8' }).trim()

const humanize = (slug: string) => slug.replace(/-/g, ' ')

export function evalRows(files: string[]): { id: string; spec: string; what: string }[] {
  return files
    .filter((f) => f.endsWith('.spec.ts'))
    .sort()
    .map((f) => {
      const m = f.match(/^(F\d+)-(.+)\.spec\.ts$/)
      return { id: m?.[1] ?? f, spec: `features/${f}`, what: humanize(m?.[2] ?? f) }
    })
}

export function evalSection(features: string[], phase1Count: number): string {
  const rows = evalRows(features)
  return [
    '### Features',
    '',
    '| Feature | Spec File | What It Tests |',
    '|---------|-----------|---------------|',
    ...rows.map((r) => `| ${r.id} | \`${r.spec}\` | ${r.what} |`),
    '',
    '### Substrate floor',
    '',
    `\`phase-0/floor.spec.ts\` and the ${phase1Count} \`phase-1/*.spec.ts\` specs assert the schema floor. They gate every migration; run them with the feature specs.`,
  ].join('\n')
}

const START = '<!-- eval-table:start (generated by npm run docs:regen) -->'
const END = '<!-- eval-table:end -->'

export function spliceChecklist(text: string, section: string): string {
  const a = text.indexOf(START)
  const b = text.indexOf(END)
  if (a === -1 || b === -1) throw new Error('TEST-CHECKLIST.md is missing its eval-table markers')
  return text.slice(0, a + START.length) + '\n\n' + section + '\n\n' + text.slice(b)
}

export function buildLogIndex(): string {
  const weeks = readdirSync('build-log', { withFileTypes: true })
    .filter((d) => d.isDirectory() && /^20\d\d-W\d\d$/.test(d.name))
    .map((d) => d.name)
  const single = readdirSync('build-log').filter((f) => /^20\d\d-W\d\d\.md$/.test(f)).map((f) => f.replace('.md', ''))
  const rows = [...weeks, ...single]
    .sort()
    .reverse()
    .map((w) => {
      const isDir = weeks.includes(w)
      const path = isDir ? `build-log/${w}` : `build-log/${w}.md`
      const n = isDir ? readdirSync(path).filter((f) => f.endsWith('.md')).length : 1
      const dates = git(['log', '--diff-filter=A', '--format=%cs', '--', path]).split('\n').filter(Boolean).sort()
      return `| ${w} | [${isDir ? 'folder' : 'file'}](${path}${isDir ? '/' : ''}) | ${n} | ${dates[0] ?? ''} | ${dates.at(-1) ?? ''} |`
    })
  return [
    '# BUILD-LOG: socialus-web',
    '',
    '*Generated by `npm run docs:regen` (`scripts/regen-docs.ts`) from `build-log/`. Do not edit by hand.*',
    '',
    'One file per ticket: `build-log/YYYY-WNN/<ticket>-<slug>.md`. Never append to a shared weekly file, because two branches then write the same path and every merge conflicts every other open PR. The full rule is in `CLAUDE.md` § Naming.',
    '',
    'Order is git: `git log --follow build-log/` is the timeline. Product and strategy notes live in `socialus-plan` (`DECISIONS.md`); there is no JOURNAL.md.',
    '',
    '## Weeks, newest first',
    '',
    '| Week | Where | Entries | First entry added | Last entry added |',
    '|------|-------|---------|--------------|-------------|',
    ...rows,
    '',
  ].join('\n')
}

function main() {
  const features = readdirSync('evals/features')
  const phase1 = readdirSync('evals/phase-1').filter((f) => f.endsWith('.spec.ts')).length
  const checklist = spliceChecklist(readFileSync('TEST-CHECKLIST.md', 'utf8'), evalSection(features, phase1))
  const log = buildLogIndex()
  if (process.argv.includes('--check')) {
    const stale = (readFileSync('TEST-CHECKLIST.md', 'utf8') !== checklist ? ['TEST-CHECKLIST.md'] : []).concat(
      existsSync('BUILD-LOG.md') && readFileSync('BUILD-LOG.md', 'utf8') === log ? [] : ['BUILD-LOG.md'],
    )
    if (stale.length) {
      console.error(`out of date: ${stale.join(', ')}. Run: npm run docs:regen`)
      process.exit(1)
    }
    console.log('generated docs are current')
    return
  }
  writeFileSync('TEST-CHECKLIST.md', checklist)
  writeFileSync('BUILD-LOG.md', log)
  console.log('wrote BUILD-LOG.md and TEST-CHECKLIST.md')
}

if (process.argv[1]?.endsWith('regen-docs.ts')) main()
