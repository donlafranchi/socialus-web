// Regenerates the docs that can be derived from the repo, so nobody maintains them:
//   TEST-CHECKLIST.md the Playwright eval table (the region between the eval-table markers)
//
// Run: npm run docs:regen            (rewrite it)
//      npm run docs:regen -- --check (exit 1 if it is out of date)
// The weekly regen-doc-inventory skill runs this, then npm run docs:inventory.

import { readdirSync, readFileSync, writeFileSync } from 'node:fs'

const humanize = (slug: string) => slug.replace(/-/g, ' ')

export function evalRows(files: string[]): { id: string; spec: string; what: string }[] {
  return files
    .filter((f) => f.endsWith('.spec.ts'))
    .sort()
    .map((f) => {
      const m = f.match(/^(F\d+)-(.+)\.spec\.ts$/)
      return { id: m?.[1] ?? f, spec: `features/${f}`, what: humanize(m?.[2] ?? f) }
    })
}

export function evalSection(features: string[], phase1Count: number): string {
  const rows = evalRows(features)
  return [
    '### Features',
    '',
    '| Feature | Spec File | What It Tests |',
    '|---------|-----------|---------------|',
    ...rows.map((r) => `| ${r.id} | \`${r.spec}\` | ${r.what} |`),
    '',
    '### Substrate floor',
    '',
    `\`phase-0/floor.spec.ts\` and the ${phase1Count} \`phase-1/*.spec.ts\` specs assert the schema floor. They gate every migration; run them with the feature specs.`,
  ].join('\n')
}

const START = '<!-- eval-table:start (generated by npm run docs:regen) -->'
const END = '<!-- eval-table:end -->'

export function spliceChecklist(text: string, section: string): string {
  const a = text.indexOf(START)
  const b = text.indexOf(END)
  if (a === -1 || b === -1) throw new Error('TEST-CHECKLIST.md is missing its eval-table markers')
  return text.slice(0, a + START.length) + '\n\n' + section + '\n\n' + text.slice(b)
}

function main() {
  const features = readdirSync('evals/features')
  const phase1 = readdirSync('evals/phase-1').filter((f) => f.endsWith('.spec.ts')).length
  const checklist = spliceChecklist(readFileSync('TEST-CHECKLIST.md', 'utf8'), evalSection(features, phase1))
  if (process.argv.includes('--check')) {
    if (readFileSync('TEST-CHECKLIST.md', 'utf8') !== checklist) {
      console.error('out of date: TEST-CHECKLIST.md. Run: npm run docs:regen')
      process.exit(1)
    }
    console.log('generated docs are current')
    return
  }
  writeFileSync('TEST-CHECKLIST.md', checklist)
  console.log('wrote TEST-CHECKLIST.md')
}

if (process.argv[1]?.endsWith('regen-docs.ts')) main()
