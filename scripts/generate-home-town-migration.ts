#!/usr/bin/env tsx
// Writes supabase/migrations/<version>_home_town.sql: members.home_market_key / home_town, and the zip → Census Place
// table (`zip_place`) for the zips of the Sacramento market's four counties (F103.5, #695). A zip's home town is the
// Census Place (city, town or CDP) holding the largest land share of the zip, provided it holds at least a tenth of the
// zip's land; otherwise the county remainder (no place). Why a tenth: by land area most zips are mostly outside any place
// (Davis's is 76% rural), so "largest part wins" would call nearly everyone a county remainder. A population weighting
// (Census blocks) would be better; this is the stand-in. Census now, HUD later (the PM, 2026-10-12, #693).
//   usage: tsx scripts/generate-home-town-migration.ts <version> [--local <dir>]
import { writeFileSync, readFileSync, existsSync } from 'node:fs'
import { resolve, dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const REL = 'https://www2.census.gov/geo/docs/maps-data/data/rel2020/zcta520'
// Sacramento, Yolo, Placer, El Dorado: the open market's counties. Towns are loaded for open markets.
const COUNTIES = new Set(['06067', '06113', '06061', '06017'])

const [version, flag, dir] = process.argv.slice(2)
if (!version) throw new Error('usage: generate-home-town-migration.ts <version> [--local <dir>]')

async function text(name: string): Promise<string> {
  if (flag === '--local' && dir && existsSync(join(dir, name))) return readFileSync(join(dir, name), 'utf8')
  const res = await fetch(`${REL}/${name}`)
  if (!res.ok) throw new Error(`${name}: ${res.status}`)
  return res.text()
}
const rows = (t: string) => t.replace(/^﻿/, '').split(/\r?\n/).filter(Boolean).map((l) => l.split('|'))
const col = (h: string[], n: string) => {
  const i = h.indexOf(n)
  if (i < 0) throw new Error(`missing column ${n}`)
  return i
}
/** "Granite Bay CDP" → "Granite Bay", "Roseville city" → "Roseville". */
const plain = (n: string) => n.replace(/ (CDP|city|town|village|borough|municipality)$/i, '')

async function main() {
  const counties = rows(await text('tab20_zcta520_county20_natl.txt'))
  const ch = counties[0]!
  const [cz, cg, ca] = [col(ch, 'GEOID_ZCTA5_20'), col(ch, 'GEOID_COUNTY_20'), col(ch, 'AREALAND_PART')]
  const best = new Map<string, { id: string; area: number }>()
  for (const r of counties.slice(1)) {
    if (!/^\d{5}$/.test(r[cz]!)) continue
    const a = Number(r[ca])
    const cur = best.get(r[cz]!)
    if (!cur || a > cur.area || (a === cur.area && r[cg]! < cur.id)) best.set(r[cz]!, { id: r[cg]!, area: a })
  }
  const zips = new Set([...best].filter(([, v]) => COUNTIES.has(v.id)).map(([z]) => z))

  const places = rows(await text('tab20_zcta520_place20_natl.txt'))
  const h = places[0]!
  const [pz, pg, pn, pa] = [col(h, 'GEOID_ZCTA5_20'), col(h, 'GEOID_PLACE_20'), col(h, 'NAMELSAD_PLACE_20'), col(h, 'AREALAND_PART')]
  // The largest place part wins; a tie goes to the lower place code so a zip always gives the same answer.
  const zipLand = col(h, 'AREALAND_ZCTA5_20')
  const MIN_SHARE = 0.1
  const town = new Map<string, { geoid: string; name: string; area: number }>()
  for (const z of zips) town.set(z, { geoid: '', name: '', area: 0 })
  for (const r of places.slice(1)) {
    const zip = r[pz]!
    const geoid = r[pg] ?? ''
    if (!zips.has(zip) || !geoid) continue
    const area = Number(r[pa])
    if (area < MIN_SHARE * Number(r[zipLand])) continue
    const cur = town.get(zip)!
    if (area > cur.area || (area === cur.area && geoid < cur.geoid)) town.set(zip, { geoid, name: plain(r[pn] ?? ''), area })
  }

  const q = (s: string) => `'${s.replace(/'/g, "''")}'`
  const lines: string[] = [
    `-- F103.5 (#695): a member in an open market has a home town: the Census Place their zip mostly lies in, else the county remainder.`,
    `-- Generated by scripts/generate-home-town-migration.ts from the Census 2020 ZCTA relationship files (Census now, HUD later).`,
    ``,
    `alter table public.members`,
    `  add column home_market_key text,`,
    `  add column home_town text,`,
    `  add column home_town_geoid text;`,
    `comment on column public.members.home_market_key is 'F103.5: the market the zip decided (a named market or county-<fips>). Re-resolved when the zip changes on You. Never shown to another member (members are readable by their owner only).';`,
    `comment on column public.members.home_town is 'F103.5: the Census Place (city, town or CDP) the zip mostly lies in; null in a county remainder or a market that is not open yet. Never shown to another member.';`,
    ``,
    `create table public.zip_place (`,
    `  zip          text primary key references public.zip_county(zip),`,
    `  -- Null: the largest part of the zip lies in no place, so the home town is the county remainder.`,
    `  place_geoid  text check (place_geoid is null or place_geoid ~ '^[0-9]{7}$'),`,
    `  place_name   text`,
    `);`,
    `alter table public.zip_place enable row level security;`,
    `create policy zip_place_select_public on public.zip_place for select using (true);`,
    ``,
    `insert into public.zip_place (zip, place_geoid, place_name) values`,
    [...town].sort(([a], [b]) => (a < b ? -1 : 1)).map(([zip, t]) => `(${q(zip)},${t.geoid ? q(t.geoid) : 'null'},${t.geoid ? q(t.name) : 'null'})`).join(',\n') + ';',
    ``,
  ]
  lines.push(
    `-- Where a zip lands: its market, and its home town when that market is open (towns are loaded for open markets).`,
    `create function public.zip_home(p_zip text)`,
    `returns table (market_key text, town_geoid text, town_name text)`,
    `language sql stable set search_path = public as $$`,
    `  select k.key,`,
    `         case when m.is_open then p.place_geoid end,`,
    `         case when m.is_open then coalesce(p.place_name, 'county remainder') end`,
    `    from (select public.zip_market_key(p_zip) as key) k`,
    `    left join public.markets m on m.slug = k.key`,
    `    left join public.zip_place p on p.zip = p_zip`,
    `   where k.key is not null`,
    `$$;`,
    ``,
    `-- The day a market opens (a person's act, #616), its waiting members get a home town. Idempotent.`,
    `create function public.backfill_home_towns(p_market_key text)`,
    `returns integer language plpgsql security definer set search_path = public as $$`,
    `declare n integer;`,
    `begin`,
    `  update public.members m`,
    `     set home_market_key = x.market_key, home_town = x.town_name, home_town_geoid = x.town_geoid`,
    `    from (select mm.id, h.market_key, h.town_geoid, h.town_name`,
    `            from public.members mm cross join lateral public.zip_home(mm.zip) h`,
    `           where mm.zip is not null and mm.deleted_at is null and h.market_key = p_market_key) x`,
    `   where m.id = x.id`,
    `     and (m.home_market_key is distinct from x.market_key or m.home_town is distinct from x.town_name);`,
    `  get diagnostics n = row_count;`,
    `  return n;`,
    `end $$;`,
    `revoke all on function public.backfill_home_towns(text) from public;`,
    `grant execute on function public.backfill_home_towns(text) to service_role;`,
  )
  writeFileSync(resolve(ROOT, 'supabase', 'migrations', `${version}_home_town.sql`), lines.join('\n') + '\n')
  console.log(`wrote ${town.size} zips`)
}
main()
