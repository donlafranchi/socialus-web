// Behaviour, against seeded rows.

const safety = databaseWriteSafety(DATABASE_URL, process.env)
const WRITABLE = requireRunnable({
  claim: 'the waitlist actually rejects a second row for one person, and a metro change moves the count',
  available: safety.safe,
  remedy: `${safety.reason} Recipe in .env.local.example`,
})

describe.skipIf(!WRITABLE)('T163 — the constraint, against real rows', () => {
  const inRollback = async <T>(
    fn: (q: (sql: string, p?: unknown[]) => Promise<Record<string, unknown>[]>) => Promise<T>,
  ): Promise<T> => {
    const pool = new Pool({ connectionString: DATABASE_URL })
    const client = await pool.connect()
    try {
      await client.query('begin')
      const q = async (sql: string, p: unknown[] = []) =>
        (await client.query(sql, p)).rows as Record<string, unknown>[]
      return await fn(q)
    } finally {
      await client.query('rollback')
      client.release()
      await pool.end()
    }
  }

  const ids = async (q: (sql: string, p?: unknown[]) => Promise<Record<string, unknown>[]>) => {
    const [{ id: memberId }] = (await q(`select id from public.members limit 1`)) as { id: string }[]
    const metros = (await q(
      `select id from public.metro_polygons where slug in ('boise-city-mountain-home-ontario-id-or','reno-carson-city-gardnerville-ranchos-nv-ca') order by slug`,
    )) as { id: string }[]
    if (metros.length < 2) {
      throw new Error(`expected two seeded metros for this fixture, got ${metros.length}`)
    }
    return { memberId, a: metros[0].id, b: metros[1].id }
  }

  it('rejects a second row for the same person, at the database (c4)', async () => {
    const err = await inRollback(async (q) => {
      const { memberId, a, b } = await ids(q)
      await q(`insert into public.metro_waitlist (member_id, metro_id, role) values ($1,$2,'creator')`, [memberId, a])
      try {
        await q(`insert into public.metro_waitlist (member_id, metro_id, role) values ($1,$2,'patron')`, [memberId, b])
        return null
      } catch (e) {
        return (e as Error).message
      }
    })
    expect(err, 'a second waitlist row for one person must be rejected').toBeTruthy()
    expect(err).toMatch(/unique|duplicate/i)
  })

  it('rejects a role that is neither creator nor patron', async () => {
    const err = await inRollback(async (q) => {
      const { memberId, a } = await ids(q)
      try {
        await q(`insert into public.metro_waitlist (member_id, metro_id, role) values ($1,$2,'lurker')`, [memberId, a])
        return null
      } catch (e) {
        return (e as Error).message
      }
    })
    expect(err).toBeTruthy()
  })

  it('cascades: removing the member removes their waitlist row', async () => {
    // Its own throwaway member, not the first one in the table: an
    // established member cannot be deleted at all (place_events restricts it),
    // so reusing one tests the wrong constraint and fails for the wrong reason.
    const remaining = await inRollback(async (q) => {
      const { a } = await ids(q)
      const [{ id: memberId }] = (await q(
        `insert into public.members (handle, display_name)
         values ('t163-cascade', 'T163 Cascade') returning id`,
      )) as { id: string }[]
      await q(`insert into public.metro_waitlist (member_id, metro_id, role) values ($1,$2,'patron')`, [memberId, a])
      await q(`delete from public.members where id = $1`, [memberId])
      return await q(`select id from public.metro_waitlist where member_id = $1`, [memberId])
    })
    expect(remaining).toEqual([])
  })

  it('counters recompute to the same numbers as the rows they summarise (c6)', async () => {
    // The counters are maintained by the handler rather than derived at read
    // time, so the thing worth testing is that the two agree.
    const rows = await inRollback(async (q) => {
      const { memberId, a } = await ids(q)
      await q(`insert into public.metro_waitlist (member_id, metro_id, role) values ($1,$2,'creator')`, [memberId, a])
      await q(`update public.metro_polygons set creator_count = creator_count + 1 where id = $1`, [a])
      return await q(
        `select m.creator_count,
                (select count(*) from public.metro_waitlist w
                  where w.metro_id = m.id and w.role = 'creator') as actual
           from public.metro_polygons m where m.id = $1`,
        [a],
      )
    })
    expect(Number(rows[0].creator_count)).toBe(Number(rows[0].actual))
  })
})
